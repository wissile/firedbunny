#!/usr/bin/env python3
"""Render lesson narration with the Kokoro voice (af_heart, Apache-2.0 model) into public/audio/lessons/<id>.mp4.

Reads tools/narration/scripts.json (made by make-scripts.js, the same text the site's player uses), skips lessons
whose audio already matches the script hash, and regenerates src/mod-z-narration-data.js after every lesson so a
partial run is always usable.

Usage:
  node tools/narration/make-scripts.js
  python3 tools/narration/render.py --model DIR [--max-minutes 100] [--ids l-a,l-b] [--voice af_heart] [--speed 1.0]
DIR holds kokoro-v1.0.onnx and voices-v1.0.bin (https://github.com/thewh1teagle/kokoro-onnx/releases).
"""
import argparse, json, os, subprocess, sys, tempfile, time

import numpy as np
import soundfile as sf

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
HERE = os.path.join(ROOT, 'tools', 'narration')
OUT = os.path.join(ROOT, 'public', 'audio', 'lessons')
MANIFEST = os.path.join(HERE, 'manifest.json')
DATA_JS = os.path.join(ROOT, 'src', 'mod-z-narration-data.js')
SR = 24000
GAP_PARA, GAP_CHAPTER, LEAD = 0.45, 0.9, 0.25


def load_manifest():
    try:
        with open(MANIFEST) as f:
            return json.load(f)
    except FileNotFoundError:
        return {}


def write_outputs(man):
    with open(MANIFEST, 'w') as f:
        json.dump(man, f, indent=1, sort_keys=True)
    data = {k: {'file': v['file'], 'dur': v['dur'], 'chapters': v['chapters'], 'hash': v['hash']} for k, v in sorted(man.items())}
    js = ('/* Generated by tools/narration/render.py. Do not edit by hand.\n'
          '   Recorded lesson narration (Kokoro TTS, voice af_heart). The player is in mod-z-narration.js. */\n'
          'window.SML.narration = ' + json.dumps(data, separators=(',', ':')) + ';\n')
    with open(DATA_JS, 'w') as f:
        f.write(js)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--model', required=True)
    ap.add_argument('--max-minutes', type=float, default=0, help='stop starting new lessons after this many minutes')
    ap.add_argument('--ids', default='')
    ap.add_argument('--voice', default='af_heart')
    ap.add_argument('--speed', type=float, default=1.0)
    ap.add_argument('--bitrate', default='40k')
    a = ap.parse_args()

    from kokoro_onnx import Kokoro
    k = Kokoro(os.path.join(a.model, 'kokoro-v1.0.onnx'), os.path.join(a.model, 'voices-v1.0.bin'))
    with open(os.path.join(HERE, 'scripts.json')) as f:
        scripts = json.load(f)
    want = set(filter(None, a.ids.split(',')))
    man = load_manifest()
    os.makedirs(OUT, exist_ok=True)
    t_start = time.time()
    done = 0
    todo = [s for s in scripts if (not want or s['id'] in want)
            and not (s['id'] in man and man[s['id']]['hash'] == s['hash'] and os.path.exists(os.path.join(ROOT, 'public', man[s['id']]['file'])))]
    print(f'{len(todo)} lessons to render', flush=True)
    for s in todo:
        if a.max_minutes and (time.time() - t_start) / 60 > a.max_minutes:
            print('time budget reached', flush=True)
            break
        t0 = time.time()
        parts, chapters, pos = [np.zeros(int(LEAD * SR), dtype=np.float32)], [], LEAD
        for ci, ch in enumerate(s['chapters']):
            if ci:
                parts.append(np.zeros(int(GAP_CHAPTER * SR), dtype=np.float32)); pos += GAP_CHAPTER
            chapters.append([round(pos, 2), ch['key']])
            for pi, para in enumerate(ch['paras']):
                if pi:
                    parts.append(np.zeros(int(GAP_PARA * SR), dtype=np.float32)); pos += GAP_PARA
                audio, sr = k.create(para, voice=a.voice, speed=a.speed, lang='en-us')
                assert sr == SR, sr
                audio = np.asarray(audio, dtype=np.float32)
                parts.append(audio); pos += len(audio) / SR
        parts.append(np.zeros(int(0.6 * SR), dtype=np.float32)); pos += 0.6
        wav = np.concatenate(parts)
        rel = f"audio/lessons/{s['id']}.mp4"
        dst = os.path.join(ROOT, 'public', rel)
        with tempfile.TemporaryDirectory() as td:
            tw = os.path.join(td, 'a.wav')
            sf.write(tw, wav, SR, subtype='PCM_16')
            tmp = os.path.join(td, 'a.mp4')
            subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', tw, '-af', 'highpass=f=70,loudnorm=I=-18:TP=-1.5:LRA=11',
                            '-ar', str(SR), '-ac', '1', '-c:a', 'aac', '-b:a', a.bitrate, '-movflags', '+faststart', tmp], check=True)
            os.replace(tmp, dst)
        man[s['id']] = {'file': rel, 'dur': round(pos, 1), 'chapters': chapters, 'hash': s['hash'], 'voice': a.voice,
                        'bytes': os.path.getsize(dst)}
        write_outputs(man)
        done += 1
        el = time.time() - t0
        print(f"{s['id']}: {pos/60:.1f} min audio in {el/60:.1f} min (rtf {el/pos:.2f}), {os.path.getsize(dst)//1024} KB", flush=True)
    # drop entries for lessons that no longer exist
    ids = {s['id'] for s in scripts}
    gone = [x for x in man if x not in ids]
    for x in gone:
        man.pop(x)
    write_outputs(man)
    left = len([s for s in scripts if not (s['id'] in man and man[s['id']]['hash'] == s['hash'])])
    print(f'rendered {done}; {left} lessons still without current audio; {(time.time()-t_start)/60:.1f} min', flush=True)


if __name__ == '__main__':
    main()
