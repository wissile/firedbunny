/* Language copies of FiredBunny's source (docs/i18n/README.md).

   node tools/i18n/make.js build LANG OUTDIR [--pseudo]
       Writes a translated copy of src/ to OUTDIR for tools/build.py (FB_SRC): every .js file with its segments
       replaced from tools/i18n/LANG/strings/*.json, plus i18n-data.js (SML.LANG settings and the on-screen labels) and
       the language's own modules from tools/i18n/LANG/content/ (country lessons, the list of hidden pages). Untranslated
       segments stay English (or pseudo-text with --pseudo, for testing). Prints what is still missing.
   node tools/i18n/make.js todo LANG [FILE ...] [--max N]
       Prints the untranslated segments (JSON {key: english}) of the given source files (default: all), for translating.
   node tools/i18n/make.js add LANG FILE.json
       Merges translations {key: text} into tools/i18n/LANG/strings/<source file>.json (by the key's source file).
   node tools/i18n/make.js stats [LANG]
       Words translated and missing per language and file.

   tools/i18n/LANG/strings/<file>.json holds {key: {en, t}} for the segments of src/<file>: the English is kept next to the
   translation so a reviewer can read both, and a changed English sentence gets a new key (the old entry is reported as
   stale and can be deleted). */
'use strict';
const fs = require('fs'), path = require('path');
const { extract, apply } = require('./segments');
const ROOT = path.join(__dirname, '..', '..');
const SRC = path.join(ROOT, 'src');
const LANGS = JSON.parse(fs.readFileSync(path.join(__dirname, 'langs.json'), 'utf8'));
const words = (s) => (String(s).replace(/<[^>]+>|\{\d+\}/g, ' ').match(/[A-Za-zÀ-ÿ]+/g) || []).length;
const srcFiles = () => fs.readdirSync(SRC).filter((f) => f.endsWith('.js')).sort();
const dir = (lang, ...p) => path.join(__dirname, lang, ...p);

function loadStrings(lang) {
  const d = dir(lang, 'strings'), all = {}, byFile = {};
  if (!fs.existsSync(d)) return { all, byFile };
  for (const f of fs.readdirSync(d).filter((f) => f.endsWith('.json'))) {
    const j = JSON.parse(fs.readFileSync(path.join(d, f), 'utf8'));
    byFile[f.replace(/\.json$/, '')] = j;
    for (const [k, v] of Object.entries(j)) if (v && typeof v.t === 'string' && v.t.trim()) all[k] = v.t;
  }
  return { all, byFile };
}

function segmentsOf(file) { return extract(fs.readFileSync(path.join(SRC, file), 'utf8'), file); }

const ACC = { a: 'à', e: 'é', i: 'î', o: 'ö', u: 'ü', A: 'Å', E: 'É', I: 'Î', O: 'Ö', U: 'Û', c: 'ç', n: 'ñ', s: 'š', y: 'ÿ' };
const pseudo = (en) => '⟦' + en.split(/(<[^>]*>|\{\d+\}|&[a-z#0-9]+;)/).map((p, i) => (i % 2 ? p : p.replace(/[aeiouAEIOUcnsy]/g, (c) => ACC[c]))).join('') + '⟧';

function build(lang, out, opts) {
  const L = LANGS[lang];
  if (!L || L.paused) throw new Error(`language ${lang} is unknown or paused`);
  const { all } = loadStrings(lang);
  fs.rmSync(out, { recursive: true, force: true });
  fs.cpSync(SRC, out, { recursive: true });
  const rt = {}; let done = 0, missingW = 0, doneW = 0, bad = [];
  for (const f of srcFiles()) {
    const src = fs.readFileSync(path.join(SRC, f), 'utf8');
    const segs = extract(src, f);
    const dict = Object.assign({}, all);
    for (const g of segs) {
      if (dict[g.key] == null && opts.pseudo) dict[g.key] = pseudo(g.en);
      if (dict[g.key] == null) missingW += words(g.en); else { done++; doneW += words(g.en); }
      if (g.runtime && dict[g.key] != null) rt[g.en] = dict[g.key];
    }
    const r = apply(src, f, dict);
    bad = bad.concat(r.bad);
    fs.writeFileSync(path.join(out, f), r.out);
  }
  // the language's own modules (country lessons, hidden pages): loaded after every other module
  const cdir = dir(lang, 'content');
  if (fs.existsSync(cdir)) for (const f of fs.readdirSync(cdir).filter((f) => f.endsWith('.js')).sort()) fs.copyFileSync(path.join(cdir, f), path.join(out, `mod-zz-${lang}-${f}`));
  let frozen = {};
  try { frozen = JSON.parse(fs.readFileSync(dir(lang, 'frozen.json'), 'utf8')); } catch (e) {}
  let pat = [];
  try { pat = JSON.parse(fs.readFileSync(dir(lang, 'patterns.json'), 'utf8')).patterns || []; } catch (e) {}
  const LANG = Object.assign({ code: lang, frozen }, L);
  delete LANG._why; delete LANG._about;
  fs.writeFileSync(path.join(out, 'i18n-data.js'),
    `/* Generated by tools/i18n/make.js for ${lang}. */\n(function () { const SML = (window.SML = window.SML || {});\n` +
    `SML.LANG = ${JSON.stringify(LANG)};\nSML.I18N_RT = ${JSON.stringify(rt)};\nSML.I18N_PAT = ${JSON.stringify(pat)};\n})();\n`);
  console.log(`i18n ${lang}: ${done} segments translated (${doneW} words), ${missingW} words still English${opts.pseudo ? ' (pseudo-text)' : ''}, ${bad.length} translations refused (tags or placeholders differ)`);
  for (const b of bad.slice(0, 10)) console.log(`  refused ${b.file}:${b.line} [${b.key}] ${JSON.stringify(b.tr).slice(0, 120)}`);
  return { done, missingW, bad };
}

function todo(lang, files, max) {
  const { all } = loadStrings(lang);
  const out = {}; let n = 0;
  for (const f of files.length ? files : srcFiles()) {
    for (const g of segmentsOf(f)) {
      if (all[g.key] != null || out[g.key] != null) continue;
      out[g.key] = g.en; if (++n >= max) break;
    }
    if (n >= max) break;
  }
  process.stdout.write(JSON.stringify(out, null, 1) + '\n');
}

function add(lang, file) {
  const tr = JSON.parse(fs.readFileSync(file, 'utf8'));
  const owner = {}; // key -> {file, en}
  for (const f of srcFiles()) for (const g of segmentsOf(f)) if (!owner[g.key]) owner[g.key] = { f, en: g.en };
  const { byFile } = loadStrings(lang);
  let n = 0, unknown = 0;
  for (const [k, t] of Object.entries(tr)) {
    const o = owner[k]; if (!o) { unknown++; continue; }
    const j = (byFile[o.f] = byFile[o.f] || {});
    j[k] = { en: o.en, t }; n++;
  }
  fs.mkdirSync(dir(lang, 'strings'), { recursive: true });
  for (const [f, j] of Object.entries(byFile)) {
    const sorted = Object.fromEntries(Object.keys(j).sort().map((k) => [k, j[k]]));
    fs.writeFileSync(dir(lang, 'strings', f + '.json'), JSON.stringify(sorted, null, 1) + '\n');
  }
  console.log(`added ${n} translations to ${lang}${unknown ? `, ${unknown} unknown keys skipped` : ''}`);
}

function stats(only) {
  const files = srcFiles();
  const segs = Object.fromEntries(files.map((f) => [f, segmentsOf(f)]));
  for (const lang of Object.keys(LANGS).filter((l) => !l.startsWith('_') && !LANGS[l].paused && (!only || l === only))) {
    const { all, byFile } = loadStrings(lang);
    let tw = 0, mw = 0; const rows = [];
    const live = new Set();
    for (const f of files) {
      let a = 0, b = 0; const seen = new Set();
      for (const g of segs[f]) { if (seen.has(g.key)) continue; seen.add(g.key); live.add(g.key); if (all[g.key] != null) a += words(g.en); else b += words(g.en); }
      tw += a; mw += b; if (b) rows.push([f, a, b]);
    }
    const stale = Object.values(byFile).reduce((n, j) => n + Object.keys(j).filter((k) => !live.has(k)).length, 0);
    console.log(`${lang}: ${tw} words translated, ${mw} to go (${Math.round((100 * tw) / Math.max(1, tw + mw))}%)${stale ? `, ${stale} stale entries` : ''}`);
    if (only) rows.sort((x, y) => y[2] - x[2]).slice(0, 40).forEach(([f, a, b]) => console.log(`  ${f}: ${a} done, ${b} to go`));
  }
}

const [cmd, lang, ...rest] = process.argv.slice(2);
if (cmd === 'build') build(lang, rest[0], { pseudo: rest.includes('--pseudo') });
else if (cmd === 'todo') { const mi = rest.indexOf('--max'); const max = mi >= 0 ? +rest[mi + 1] : Infinity; todo(lang, rest.filter((x, i) => !x.startsWith('--') && (mi < 0 || i !== mi + 1)), max); }
else if (cmd === 'add') add(lang, rest[0]);
else if (cmd === 'stats') stats(lang);
else console.log('usage: make.js build|todo|add|stats ...');
module.exports = { build, loadStrings };
