#!/usr/bin/env python3
"""Copy the site's three fonts into public/fonts/ and write src/fonts.css, so the website needs no font CDN and works
offline. Source: the Fontsource npm packages (SIL Open Font License), which carry Google Fonts' files and subsets.

  npm install --prefix DIR @fontsource/bebas-neue @fontsource/ibm-plex-mono @fontsource/ibm-plex-sans
  python3 tools/vendor_fonts.py DIR/node_modules/@fontsource

Only the weights the site uses, and only the latin, latin-ext and greek subsets (the page uses a few Greek letters such
as sigma). The claude.ai artifact copy keeps loading Google Fonts, which artifacts allow.
"""
import os, re, shutil, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WANT = {
    'bebas-neue': [('400', 'normal')],
    'ibm-plex-mono': [(w, 'normal') for w in ('400', '500', '600', '700')],
    'ibm-plex-sans': [(w, 'normal') for w in ('400', '500', '600', '700')] + [('700', 'italic')],
}
SUBSETS = ('latin', 'latin-ext', 'greek')


def main(src):
    out_dir = os.path.join(ROOT, 'public', 'fonts')
    os.makedirs(out_dir, exist_ok=True)
    rules = ['/* Generated by tools/vendor_fonts.py: self-hosted fonts (SIL Open Font License, see /fonts/). */']
    for fam, variants in WANT.items():
        pkg = os.path.join(src, fam)
        lic = os.path.join(pkg, 'LICENSE')
        if os.path.exists(lic):
            shutil.copyfile(lic, os.path.join(out_dir, f'LICENSE-{fam}.txt'))
        for weight, style in variants:
            css = open(os.path.join(pkg, weight + ('-italic' if style == 'italic' else '') + '.css'), encoding='utf-8').read()
            for block in re.findall(r'@font-face\s*{[^}]*}', css):
                m = re.search(r'files/(' + re.escape(fam) + r'-([a-z-]+)-' + weight + '-' + style + r')\.woff2', block)
                if not m or m.group(2) not in SUBSETS:
                    continue
                name = m.group(1) + '.woff2'
                shutil.copyfile(os.path.join(pkg, 'files', name), os.path.join(out_dir, name))
                family = re.search(r"font-family:\s*'([^']+)'", block).group(1)
                urange = re.search(r'unicode-range:\s*([^;]+);', block).group(1).strip()
                rules.append(f"@font-face{{font-family:'{family}';font-style:{style};font-weight:{weight};font-display:swap;"
                             f"src:url(/fonts/{name}) format('woff2');unicode-range:{urange}}}")
    with open(os.path.join(ROOT, 'src', 'fonts.css'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(rules) + '\n')
    print(len(rules) - 1, 'font files ->', out_dir)


if __name__ == '__main__':
    main(sys.argv[1])
